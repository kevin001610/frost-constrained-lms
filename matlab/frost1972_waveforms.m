function [X, info] = frost1972_waveforms(S, Nsnap, seed, M)
%FROST1972_WAVEFORMS  Time-domain generation of the tap-voltage snapshots X(k).
%
%   [X, info] = FROST1972_WAVEFORMS(S, Nsnap, seed, M)
%   Generates, for every source of Table I, a Gaussian random waveform whose
%   autocorrelation is exactly the model r(t) in frost1972_acf (spectral
%   shaping of white noise on a grid of M samples per tau), delays it to every
%   sensor and every tap (sensor k: k*tau*sin(theta); tap j: j*tau), adds white
%   noise of power S.Pwhite per tap, and returns Nsnap snapshots taken every
%   S.Delta tau apart (> 58 tau as in the paper, so the snapshots are
%   practically independent).  X is KJ x Nsnap.
%
%   This is the route Frost describes in Sec. VII ("generated by a pseudo-
%   Gaussian generator and filtered to give them the proper spatial and
%   temporal correlations").  It is independent of the analytic Rxx in
%   frost1972_setup, so comparing the sample covariance of X with S.Rxx is a
%   genuine check of the analytic model (see frost1972_verify.m).

if nargin < 4, M = 100; end       % oversampling: samples per tau
rng(seed);

Lsnap = S.Delta*M;                      % samples between snapshots
maxDelay = (S.J-1)*M + (S.K-1)*M;       % worst-case delay in samples
Ntot = Nsnap*Lsnap + maxDelay + 1;
Nfft = 2^nextpow2(Ntot);

% frequency grid (cycles per tau) of the FFT
f = (0:Nfft-1)/Nfft*M;  f(f >= M/2) = f(f >= M/2) - M;

X = zeros(S.N, Nsnap);
snapIdx = maxDelay + 1 + (0:Nsnap-1)*Lsnap;   % sample index of each snapshot
info.psd = cell(1, numel(S.src));
for m = 1:numel(S.src)
    % --- PSD of this source = FT of the model autocorrelation --------------
    tgrid = (-S.Tc*M:S.Tc*M)/M;                          % lags in tau
    r = S.src(m).P * frost1972_acf(tgrid, S.src(m).fc, S.src(m).B, S.Tc);
    rfull = zeros(1, Nfft);
    rfull(1:numel(tgrid)) = r;                           % will be shifted to centre at 0
    rfull = circshift(rfull, -(S.Tc*M));                 % lag 0 at index 1
    Sf = real(fft(rfull)) / M;                           % PSD (power per unit frequency)
    Sf(Sf < 0) = 0;                                      % guard tiny negative round-off
    info.psd{m} = struct('f', f, 'S', Sf);
    % --- shape white Gaussian noise so that its autocorrelation is r -------
    w  = randn(1, Nfft);
    Hf = sqrt(Sf * M);                                   % |H|^2 = S(f)*M so that var = r(0)
    s  = real(ifft(fft(w) .* Hf));                       % Gaussian waveform, ACF = r (circular)
    % --- distribute to the taps with the proper delays ---------------------
    d  = sind(S.src(m).theta);
    for jtap = 0:S.J-1
        for ksen = 0:S.K-1
            n   = jtap*S.K + ksen + 1;                   % weight index
            del = round((jtap + ksen*d) * M);            % delay in samples
            X(n, :) = X(n, :) + s(snapIdx - del);
        end
    end
end
X = X + sqrt(S.Pwhite)*randn(S.N, Nsnap);               % white noise per tap
info.M = M; info.seed = seed;
end
